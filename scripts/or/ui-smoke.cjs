const { chromium } = require('playwright');
const dir = process.argv[2];
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 1440, height: 1000 }, storageState: dir + '/state.json' });
  const p = await ctx.newPage();
  const errors = []; p.on('pageerror', e => errors.push(e.message));
  const base = 'http://localhost:3000/app/org/default/brand/demo-kowhai-plumbing/online-reset';
  await p.goto(base, { waitUntil: 'networkidle' });
  await p.getByText('Buyer-Question Coverage').waitFor({ timeout: 60000 });
  await p.screenshot({ path: dir + '/02-visibility.png', fullPage: true });
  await p.getByRole('button', { name: 'Answer 1' }).first().click();
  await p.getByText('The stored answer behind the figures').waitFor();
  await p.waitForTimeout(800);
  await p.screenshot({ path: dir + '/03-evidence.png' });
  await p.keyboard.press('Escape');
  await p.getByRole('tab', { name: 'Audit' }).click();
  await p.getByText('Brand Completeness').waitFor();
  await p.screenshot({ path: dir + '/04-audit.png', fullPage: true });
  await p.getByRole('tab', { name: 'Opportunities' }).click();
  await p.getByText('Recalculate').waitFor();
  await p.screenshot({ path: dir + '/05-opportunities.png', fullPage: true });
  const card = p.locator('[data-slot="card"]', { hasText: 'Missing page: "Emergency plumbing"' }).first();
  await card.getByRole('button', { name: 'Draft a Fix' }).click();
  await p.waitForTimeout(2500);
  await p.getByRole('tab', { name: 'Content and Approvals' }).click();
  await p.getByText('Approval Queue').waitFor();
  const row = p.getByRole('row', { name: /Emergency plumbing/ }).first();
  await row.getByRole('button', { name: 'Open' }).click();
  const ta = p.locator('textarea');
  await ta.waitFor();
  const text = await ta.inputValue();
  await ta.fill(text.replaceAll("[REVIEWER: answer from the business's own knowledge before approving.]", 'Yes — we take after-hours emergency call-outs across Christchurch.'));
  await p.getByRole('button', { name: 'Save Revision' }).click();
  await p.waitForTimeout(2000);
  await p.screenshot({ path: dir + '/06-editor-qa.png' });
  await p.getByRole('button', { name: 'Request Approval' }).click();
  await p.waitForTimeout(2000);
  await p.keyboard.press('Escape');
  await p.waitForTimeout(1000);
  await p.screenshot({ path: dir + '/07-approval-queue.png', fullPage: true });
  await p.getByRole('button', { name: 'Approve' }).first().click();
  await p.waitForTimeout(2500);
  await p.screenshot({ path: dir + '/08-approved.png', fullPage: true });
  await p.getByRole('tab', { name: 'Report' }).click();
  await p.waitForTimeout(3000);
  await p.screenshot({ path: dir + '/09-report.png' });
  console.log('page errors:', JSON.stringify(errors));
  await b.close();
})().catch(e => { console.error(e.message); process.exit(1); });
